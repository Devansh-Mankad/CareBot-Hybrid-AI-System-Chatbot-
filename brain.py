# Gemini Chat Creation
def create_chat(chat_history):
    """
    Creates Gemini chat with previous
    conversation history.
    """

    history = build_gemini_history(chat_history)
    return client.chats.create(
        model=MODEL_NAME,
        config=types.GenerateContentConfig(
            system_instruction=SYSTEM_RULES,
            temperature=0.3
        ),
        history=history
    )

# Gemini Response
def generate_followup_response(chat_history, user_query):
    """
    Ask follow-up questions.
    """

    chat = create_chat(chat_history)
    prompt = build_followup_prompt(user_query)
    return send_to_gemini(chat, prompt)


def generate_prediction_response(
    chat_history,
    user_query,
    predictions
):
    """
    Explain Random Forest predictions.
    """

    chat = create_chat(chat_history)
    prompt = build_prediction_prompt(
        user_query,
        predictions
    )
    return send_to_gemini(chat, prompt)

# Debug Helpers
DEBUG = True
def print_predictions(predictions):
    """
    Print ML predictions to terminal.
    """

    if not DEBUG:
        return
    print("\n========== ML Predictions ==========")
    if not predictions:
        print("No predictions generated.")

    else:
        for prediction in predictions:
            print(
                f"{prediction['disease']} "
                f"({prediction['confidence']}%)"
            )
    print("====================================\n")

def print_detected_symptoms(chat_history):
    """
    Print extracted symptoms.
    Useful during development.
    """

    if not DEBUG:
        return

    symptoms = collect_symptoms(chat_history)
    detected = [
        symptom
        for symptom, value in symptoms.items()
        if value == 1
    ]

    print("\n======= Detected Symptoms =======")
    if detected:
        for symptom in detected:
            print("-", symptom)

    else:
        print("None")
    print("===============================\n")

# Pipeline Helper
def run_prediction_pipeline(chat_history):
    """
    Complete ML pipeline.
    Returns:
    predictions
    """

    print_detected_symptoms(chat_history)
    predictions = generate_ml_predictions(chat_history)
    print_predictions(predictions)
    return predictions

def classify_query(text):
    text = text.lower()

    disease_keywords = [
        "what is",
        "what are",
        "tell me about",
        "information about",
        "causes of",
        "symptoms of",
        "diabetes",
        "dengue",
        "malaria",
        "typhoid",
        "covid",
        "asthma",
        "hypertension"
    ]

    prevention_keywords = [
        "prevent",
        "prevention",
        "precaution",
        "avoid",
        "care"
    ]

    symptom_keywords = [
        "have",
        "having",
        "pain",
        "fever",
        "cough",
        "headache",
        "vomiting",
        "nausea",
        "chills",
        "dizziness"
    ]

    if any(word in text for word in prevention_keywords):
        return "prevention"

    if any(word in text for word in disease_keywords):
        return "disease_info"

    if any(word in text for word in symptom_keywords):
        return "symptom"

    return "general"

# Main Hybrid AI Function
def get_carebot_response(user_query, chat_history):
    """
    Main entry point of CareBot.

    Flow

    Greeting
        │
        ▼
    Intent Classification
        │
        ├───────────────┐
        │               │
        ▼               ▼
    Disease Info    Prevention
        │               │
        ▼               ▼
      Gemini         Gemini
        │               │
        └──────┬────────┘
               ▼
         Symptom Query
               │
               ▼
      Enough Information?
         │            │
         ▼            ▼
   Ask Questions   Random Forest
                        │
                        ▼
             Gemini explains ML results
    """

    response, handled = handle_basic_intents(user_query)
    if handled:
        return response, []

    # Initialize History
    if chat_history is None:
        chat_history = []
    
    intent = classify_query(user_query)
    
    if intent == "disease_info":

        try:

            chat = create_chat(chat_history)

            prompt = f"""
User asked:

{user_query}

Provide a structured response with:

• Overview
• Causes
• Symptoms
• Prevention
• Natural Home Remedies
• When to consult a doctor

IMPORTANT RULES:

- Never recommend medicines, tablets, injections or brand names.
- Never prescribe pharmaceutical drugs.
- Only suggest natural home remedies and lifestyle advice.
- Clearly state that only a qualified doctor can prescribe medicines.

Do NOT ask follow-up questions.
"""

            response = send_to_gemini(chat, prompt)

            return response, []

        except Exception as error:

            return (
                f"Unable to process request.\n\n{error}",
                []
            )

    # Prevention Query
    if intent == "prevention":
        try:
            chat = create_chat(chat_history)
            prompt = f"""
User asked:
{user_query}

Provide:
• Prevention
• Lifestyle advice
• Home remedies
• Risk factors

IMPORTANT RULES:

- Never recommend medicines, tablets, injections or brand names.
- Never prescribe pharmaceutical drugs.
- Only suggest natural home remedies and lifestyle advice.
- Clearly state that only a qualified doctor can prescribe medicines.

Do NOT ask follow-up questions.
"""

            response = send_to_gemini(chat, prompt)
            return response, []

        except Exception as error:
            return (
                f"Unable to process request.\n\n{error}",
                []
            )

    # Symptom Query
    if should_collect_more_information(chat_history):
        try:
            response = generate_followup_response(
                chat_history,
                user_query
            )
            return response, []

        except Exception as error:
            return (
                f"Unable to process request.\n\n{error}",
                []
            )

    # Random Forest Prediction
    predictions = run_prediction_pipeline(chat_history)
    if not predictions:

        return (
            "I couldn't identify enough symptoms to generate reliable predictions.\n\n"
            "Please describe your symptoms in more detail.",
            []
        )

    # Gemini Explanation
    try:
        response = generate_prediction_response(
            chat_history,
            user_query,
            predictions
        )
        return response, predictions

    except Exception as error:
        return (
            f"Unable to generate AI response.\n\n{error}",
            predictions
        )