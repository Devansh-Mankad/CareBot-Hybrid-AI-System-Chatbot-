# Retry Wrapper
def send_to_gemini(chat, prompt):
    """
    Retry Gemini once if
    temporary server error occurs.
    """

    for attempt in range(RETRY_COUNT):
        try:
            response = chat.send_message(prompt)
            return response.text

        except Exception as error:
            if should_retry(error) and attempt < RETRY_COUNT - 1:
                time.sleep(RETRY_DELAY)
                continue
            raise error

