# Intent Handler
def handle_basic_intents(user_query):
    """
    Returns
    response, handled
    """

    if is_greeting(user_query):
        return greeting_response(), True

    if is_thanks(user_query):
        return thanks_response(), True

    if is_goodbye(user_query):
        return goodbye_response(), True

    return None, False

# Follow-up Question Decision
def should_collect_more_information(chat_history):
    """
    Wrapper around has_enough_information().

    Easier to understand later inside
    get_carebot_response().
    """

    return not has_enough_information(chat_history)


