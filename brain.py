# Greeting Detection
def is_greeting(text: str) -> bool:
    return text.lower().strip() in SUPPORTED_GREETINGS

def is_thanks(text: str) -> bool:
    text = text.lower()
    return any(word in text for word in THANK_WORDS)

def is_goodbye(text: str) -> bool:
    text = text.lower()
    return any(word in text for word in SUPPORTED_GOODBYES)

# Conversation Helpers
def get_all_user_messages(chat_history):
    """
    Returns every user message
    merged into one string.
    """

    return " ".join(
        msg["content"]
        for msg in chat_history
        if msg["role"] == "user"
    )


def count_user_messages(chat_history):
    return len(
        [
            msg
            for msg in chat_history
            if msg["role"] == "user"
        ]
    )


def is_first_interaction(chat_history):
    return count_user_messages(chat_history) <= 1

# Symptom Collection Helper
def collect_symptoms(chat_history):
    """
    Collect symptoms from the
    ENTIRE conversation.

    This makes the Random Forest model
    much more reliable than extracting
    symptoms from only the latest message.
    """

    conversation = get_all_user_messages(chat_history)
    return extract_symptoms(conversation)

# Gemini History Builder
def build_gemini_history(chat_history):
    """
    Convert Streamlit chat history
    into Gemini Content objects.
    """
    history = []
    for msg in chat_history[:-1]:
        role = "user"
        if msg["role"] == "assistant":
            role = "model"
        history.append(
            types.Content(
                role=role,
                parts=[
                    types.Part(text=msg["content"])
                ]
            )
        )
    return history


# Retry Helper
def should_retry(error):
    error = str(error).lower()
    return (
        "503" in error
        or "unavailable" in error
        or "deadline" in error
    )


# Pretty Formatting
def prediction_to_text(predictions):
    """
    Convert ML predictions into a
    prompt-friendly format.
    """

    if not predictions:
        return "No predictions available."
    output = []

    for i, item in enumerate(predictions, start=1):
        disease = item["disease"]
        confidence = item["confidence"]
        output.append(
            f"{i}. {disease} ({confidence:.2f}%)"
        )
    return "\n".join(output)

# Voice Input
def listen_to_user(timeout=8):
    """
    Listen through the microphone and convert
    speech into text.
    """

    recognizer = sr.Recognizer()
    try:
        with sr.Microphone() as source:
            recognizer.adjust_for_ambient_noise(source, duration=1)
            print("Listening...")

            audio = recognizer.listen(
                source,
                timeout=timeout,
                phrase_time_limit=15
            )

        text = recognizer.recognize_google(audio)
        return text

    except sr.WaitTimeoutError:
        return None
    except sr.UnknownValueError:
        return None
    except sr.RequestError:
        return None
    except Exception:
        return None

# Symptom Validation
def count_detected_symptoms(symptoms_dict):
    """
    Count how many symptoms
    were detected by extract_symptoms().
    """

    return sum(
        1
        for value in symptoms_dict.values()
        if value == 1
    )


def has_enough_information(chat_history):
    """
    Decide whether enough clinical
    information exists to invoke
    the ML model.

    Current rule:

    • at least MIN_REQUIRED_SYMPTOMS
      extracted

    AND

    • at least two user turns
    """

    symptoms = collect_symptoms(chat_history)
    symptom_count = count_detected_symptoms(symptoms)
    enough_turns = count_user_messages(chat_history) >= 2
    return symptom_count >= MIN_REQUIRED_SYMPTOMS and enough_turns

# Machine Learning Prediction
def generate_ml_predictions(chat_history):
    """
    Extract symptoms from the ENTIRE
    conversation and predict diseases.
    """

    symptoms = collect_symptoms(chat_history)
    if count_detected_symptoms(symptoms) == 0:
        return []

    predictions = predict_disease(symptoms)
    cleaned = []

    for prediction in predictions:
        confidence = prediction.get("confidence", 0)
        if confidence >= 20:
            cleaned.append(prediction)
    return cleaned[:3]

